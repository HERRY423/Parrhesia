"""Matched fresh development probes plus scope and nonblocking regressions."""
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

import test_false_abstention_realistic as realistic
from parrhesia.gates import collect_lexical_advisories, contradictory_positive_evidence_text
from scripts.eval_text_advisories import DEFAULT_SUITE, evaluate

ROOT = Path(__file__).resolve().parents[1]


class TextAdvisoryTests(unittest.TestCase):
    def test_frozen_new_matched_cases(self):
        result = evaluate()
        self.assertEqual(result["summary"]["total"], 38)
        self.assertTrue(result["summary"]["all_passed"], [r for r in result["results"] if not r["passed"]])
        self.assertEqual(result["summary"]["false_advisories"], 0)
        self.assertIn("not_independent_holdout", result["status"])

    def test_scope_is_invariant_to_order_and_verbatim_quote(self):
        for focus, expected in [("The intervention increased daily walking distance.", False),
                                ("The intervention reduced adverse events.", True)]:
            efficacy = "Daily walking distance increased after rehabilitation."
            safety = "Adverse events showed no significant difference."
            for source in [efficacy + " " + safety, safety + " " + efficacy]:
                for quote in [source, safety, efficacy]:
                    with self.subTest(focus=focus, source=source, quote=quote):
                        ev = {"source_text": source, "quote": quote, "source_text_status": "complete"}
                        self.assertEqual(bool(contradictory_positive_evidence_text(ev, focus_text=focus)), expected)

    def test_primary_safety_and_current_failure_survive_scoping(self):
        texts = [
            "Reading fluency improved. The primary safety endpoint showed no significant difference.",
            "Unlike previous reports the current result showed no significant difference in reading fluency.",
            "Reading fluency showed no significant difference despite favorable safety findings.",
        ]
        for source in texts:
            self.assertIsNotNone(contradictory_positive_evidence_text(
                {"source_text": source, "quote": source}, focus_text="The intervention improves reading fluency."), source)

    def test_incomplete_history_context_does_not_erase_sole_evidence(self):
        source = "Unlike previous reports that found no treatment benefit"
        self.assertIsNotNone(contradictory_positive_evidence_text(
            {"source_text": source, "quote": source}, focus_text="The intervention improves reading fluency."))
        source = "Reading fluency improved. The primary safety endpoint showed no significant difference."
        self.assertIsNotNone(contradictory_positive_evidence_text({"source_text": source, "quote": source}))

    def test_source_cues_cannot_join_across_unrelated_clauses(self):
        for source in [
            "Symptom scores improved. The authors await collection of publication fees.",
            "An algorithm generated predictions. Virtual participants were discussed in the introduction.",
            "Computer measurements improved. Virtual patient records were not generated.",
        ]:
            ev = {"evidence_id": "E1", "source_text": source, "quote": source, "kind": "intervention", "provenance": "observed"}
            result = collect_lexical_advisories({"verdict": "supported"}, {"id": "C1", "evidence_ids": ["E1"]}, [ev])
            self.assertEqual(result, [], source)

    def test_legacy_phrase_cannot_be_created_across_clause_boundary(self):
        source = "Audit query response: no\nSupport was confirmed in a prespecified replication."
        self.assertIsNone(contradictory_positive_evidence_text(
            {"source_text": source, "quote": source}, focus_text="The method improves walking distance."))

    def test_new_cues_are_nonblocking_in_full_workflow(self):
        fixture = realistic.RealisticFalseAbstentionTests()
        fixture.setUp()
        try:
            examples = [
                ("pending-source", "Symptom measurements await collection at the next assessment.",
                 "Symptom measurements establish a symptom benefit.", "possible_outcome_pending_text"),
                ("generated-source", "Simulated participants were generated by a mathematical model to evaluate treatment response.",
                 "Patient treatment response improved in clinical testing.", "possible_evidence_kind_mismatch"),
            ]
            for slug, source, claim, hook in examples:
                adj, ver, exp, _ = fixture._run_e2e_positive(
                    slug=slug, claim_type="causal_effect", evidence_level="identified_under_assumptions",
                    family="randomized", evidence_kind="intervention", evidence_text=source,
                    quote=source, claim_text=claim, estimate="not quantified", uncertainty="not quantified",
                )
                advisories = adj["symmetry_audit"]["lexical_advisories"]
                self.assertIn(hook, {a["hook_code"] for a in advisories})
                self.assertTrue(all(a["non_blocking"] and a["severity"] == "advisory" for a in advisories))
                self.assertEqual(ver["status"], "pass")
                self.assertEqual(exp["state"], "exported")
        finally:
            fixture.tearDown()

    def test_rule_audit_exposes_overlap_and_rejects_case_literals(self):
        spec = importlib.util.spec_from_file_location("text_rule_audit", ROOT / "scripts/check-eval-leakage.py")
        checker = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(checker)
        suite = json.loads((ROOT / "docs/evaluation/stage0-cases.json").read_text("utf-8"))
        audit = checker.audit_advisory_module(suite)
        self.assertTrue(audit["no_case_literals"])
        self.assertGreater(audit["regex_overlap_field_count"], 0)
        self.assertFalse(audit["independent_holdout"])
        self.assertIn("PENDING_OUTCOME_RE", audit["regex_components"])
        self.assertTrue(checker.audit_advisory_module(json.loads(DEFAULT_SUITE.read_text("utf-8")))["no_case_literals"])
        with tempfile.TemporaryDirectory(dir=ROOT / "artifacts") as directory:
            source = Path(directory) / "injected.py"
            source.write_text('SAMPLE = "HADV-08"\n', encoding="utf-8")
            self.assertFalse(checker.audit_advisory_module(suite, source)["no_case_literals"])


if __name__ == "__main__":
    unittest.main()
